#!/usr/bin/env node
import { Command } from "commander";
import { randomUUID } from "node:crypto";
import { LocalApiClient } from "../transport/http/client.js";
import type { ReadResource } from "../application/service.js";
const program = new Command().name("contextmesh").description("Inspect and run the local ContextMesh coordination service").version("0.2.0");
const client = new LocalApiClient();
program.command("end-session").description("Recover an interrupted or stale session without completing its task")
  .requiredOption("--project <id>").requiredOption("--session <id>").requiredOption("--reason <text>")
  .option("--request-id <id>", "Stable retry identity")
  .action(async options => console.log(JSON.stringify(await client.ingest({ eventId: typeof options.requestId === "string" ? options.requestId : randomUUID(), source: "cli", type: "session_ended", projectId: options.project, sessionId: options.session, occurredAt: new Date().toISOString(), payload: { reason: options.reason } }), null, 2)));
const memory = program.command("memory").description("Inspect, revise or delete a durable memory with preserved history");
memory.command("show <id>").requiredOption("--project <id>").action(async (id, options) => console.log(JSON.stringify(await client.memoryHistory(options.project, id), null, 2)));
for (const action of ["revise", "delete"] as const) {
  const command = memory.command(action + " <id>").requiredOption("--project <id>").requiredOption("--session <id>")
    .requiredOption("--expected-version <id>", "Current version ID from memory show")
    .requiredOption("--reason <text>").option("--request-id <id>", "Stable retry identity");
  if (action === "revise") command.option("--content <text>").option("--rationale <text>").option("--file <paths...>");
  command.action(async (id, options) => {
    const body = { projectId: options.project, sessionId: options.session, requestId: options.requestId ?? randomUUID(), expectedVersionId: options.expectedVersion, reason: options.reason,
      ...(action === "revise" ? { content: options.content, rationale: options.rationale, relatedFiles: options.file } : {}) };
    console.log(JSON.stringify(await client.modifyMemory(action, id, body), null, 2));
  });
}
program.command("connect").argument("<agent>", "Agent host (codex or claude)").description("Prepare an agent connection for an ordinary Git project")
  .requiredOption("--project <id>", "Shared project ID for all peer sessions")
  .requiredOption("--repo <path>", "Repository/worktree directory")
  .requiredOption("--task <description>", "Work for this session")
  .option("--session <id>", "Unique session ID (generated by default)")
  .option("--enable-experimental-claude", "Opt in to Claude integration, which still requires live validation")
  .option("--hooks", "Include documented Codex hooks; host support and normal hook trust are required")
  .option("--json", "Output connection details as JSON")
  .action(async (agent, options) => {
    if (agent === "claude") {
      const { prepareClaudeConnection } = await import("../adapters/claude-code/connection.js");
      const connection = await prepareClaudeConnection({ projectId: options.project, repositoryPath: options.repo, task: options.task, enabled: options.enableExperimentalClaude, client });
      console.log(options.json ? JSON.stringify(connection, null, 2) : "Claude: " + (connection.enabled ? "opted in; live verification pending" : "disabled; live verification pending") + "\nArtifacts: " + connection.directory + "\n" + connection.command); return;
    }
    if (agent !== "codex") throw new Error("Supported agents: codex, claude");
    const { prepareCodexConnection } = await import("../adapters/codex/connection.js");
    const connection = await prepareCodexConnection({ projectId: options.project, repositoryPath: options.repo, task: options.task, sessionId: options.session, hooks: options.hooks, client });
    console.log(options.json ? JSON.stringify(connection, null, 2) : "Project: " + connection.projectId + "\nSession: " + connection.sessionId + "\nRun in PowerShell:\n" + connection.command + "\nOr: node " + JSON.stringify(connection.node));
  });
program.command("start").description("Start the persistent local service").action(async () => { await import("../service.js"); });
function record(value: unknown): Record<string, unknown> { return value && typeof value === "object" ? value as Record<string, unknown> : {}; }
function render(resource: string, value: unknown): string {
  if (resource === "status") {
    const state = record(record(value).state);
    const count = (key: string) => Array.isArray(state[key]) ? state[key].length : 0;
    return "ContextMesh: reachable at " + client.baseUrl + "\nStorage: " + (record(value).storageReady ? "ready" : "not ready") + "\nSessions: " + count("sessions") + " | Tasks: " + count("tasks") + " | Warnings: " + count("warnings") + " | Events: " + state.acceptedEventCount;
  }
  if (resource === "doctor") {
    const data = record(value);
    return "Service: " + data.service + "\nStorage: " + (data.storageReady ? "ready" : "not ready") + "\nGit: " + (data.git ?? "unavailable") + "\nOverall: " + (data.ok ? "ready" : "needs attention");
  }
  if (resource === "context") {
    const data = record(value);
    const items = data.items as Record<string, unknown>[];
    return "Project context: " + data.projectId + " (" + data.used + "/" + data.budget + " characters" + (data.truncated ? ", truncated" : "") + ")\n" + items.map(item => "[" + item.kind + "] " + item.summary + (item.rationale ? "\n  Why: " + item.rationale : "") + (Array.isArray(item.files) && item.files.length ? "\n  Files: " + item.files.join(", ") : "") + (item.data ? "\n  " + JSON.stringify(item.data) : "")).join("\n");
  }
  if (!Array.isArray(value) || value.length === 0) return "No " + resource + " found.";
  return value.map(entry => {
    const item = record(entry);
    if (resource === "sessions") return item.id + " | " + item.agentType + " | " + item.status + " | task: " + (item.taskId ?? "none");
    if (resource === "warnings") return item.kind + ": " + item.message;
    if (resource === "history") return item.occurredAt + " | " + item.type + " | session: " + item.sessionId + "\n  " + JSON.stringify(item.payload);
    if (resource === "tasks") return item.id + " | " + item.status + " | " + item.title;
    return item.kind + ": " + item.content + (item.rationale ? "\n  Why: " + item.rationale : "");
  }).join("\n");
}
for (const [name, resource] of [["status", "status"], ["sessions", "sessions"], ["tasks", "tasks"], ["conflicts", "warnings"], ["history", "history"], ["context", "context"], ["memories", "memories"], ["doctor", "doctor"]] as const) {
  const command = program.command(name).description("Inspect " + name + " through the running service").option("--json", "Output JSON");
  if (name !== "doctor") {
    if (name === "status") command.option("--project <id>", "Project ID");
    else command.requiredOption("--project <id>", "Project ID");
  }
  if (name === "context") command.option("--session <id>", "Exclude this session's own active task").option("--file <paths...>", "Relevant repository-relative files").option("--budget <characters>", "Maximum serialized character budget", "8000");
  if (name === "history") command.option("--limit <count>", "Maximum accepted events", "50");
  if (name === "memories") command.option("--query <text>", "Search current memories by words");
  command.action(async options => {
    const value = await client.read(resource as ReadResource, { projectId: options.project, sessionId: options.session, files: options.file, budget: options.budget, limit: options.limit, query: options.query });
    console.log(options.json ? JSON.stringify(value, null, 2) : render(resource, value));
    if (name === "doctor" && !record(value).ok) process.exitCode = 1;
  });
}
program.command("refresh").description("Inspect Git and save repository evidence").requiredOption("--project <id>").option("--session <id>").action(async options => console.log(JSON.stringify(await client.refresh({ projectId: options.project, sessionId: options.session }), null, 2)));
try { await program.parseAsync(); }
catch (error) { console.error(error instanceof Error ? error.message : "ContextMesh command failed"); process.exitCode = 1; }
